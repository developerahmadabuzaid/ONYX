using System.Text.RegularExpressions;
using Onyx.Domain.Common;
using Onyx.Domain.Content;

namespace Onyx.Domain.Media;

/// <summary>
/// Metadata of a stored media file. The binary lives in media storage (never in PostgreSQL) under a random, server-generated
/// <see cref="StorageKey"/>; the original file name is kept for display only and is never used as a path.
/// Default alt/title/caption per language: <see cref="LocalizedText.Text"/> is the alt text, <see cref="LocalizedText.Secondary"/>
/// the caption. Content can override alt text per usage.
/// </summary>
public sealed partial class MediaAsset : AuditableEntity, IAuditable
{
    public const int StorageKeyMaxLength = 120;
    public const int FileNameMaxLength = 255;
    public const int ContentTypeMaxLength = 100;
    public const int AltMaxLength = 300;
    public const int CaptionMaxLength = 500;
    public const int TitleMaxLength = 200;

    private MediaAsset()
    {
        StorageKey = string.Empty;
        OriginalFileName = string.Empty;
        ContentType = string.Empty;
        Extension = string.Empty;
        Sha256 = string.Empty;
        Texts = [];
    }

    public string StorageKey { get; private set; }

    public string OriginalFileName { get; private set; }

    public MediaKind Kind { get; private set; }

    /// <summary>MIME type verified from the file signature, not the client's claim.</summary>
    public string ContentType { get; private set; }

    public string Extension { get; private set; }

    public long SizeBytes { get; private set; }

    public int? Width { get; private set; }

    public int? Height { get; private set; }

    public string Sha256 { get; private set; }

    public string? Title { get; private set; }

    public IReadOnlyList<LocalizedText> Texts { get; private set; }

    public uint Version { get; private set; }

    /// <summary>Call before removing the record: schedules removal of the stored file through the outbox.</summary>
    public void MarkDeleted() => RaiseDomainEvent(new MediaAssetDeleted(Id, StorageKey));

    public static MediaAsset Create(
        string storageKey, string originalFileName, MediaKind kind, string contentType, string extension, long sizeBytes, int? width, int? height, string sha256)
    {
        if (!StorageKeyPattern().IsMatch(storageKey) || storageKey.Length > StorageKeyMaxLength)
        {
            throw new ArgumentException("Storage keys are generated by the server.", nameof(storageKey));
        }

        if (sizeBytes <= 0 || sha256 is not { Length: 64 })
        {
            throw new ArgumentException("A media file needs a size and a SHA-256 hash.");
        }

        return new MediaAsset
        {
            StorageKey = storageKey,
            OriginalFileName = SafeDisplayName(originalFileName),
            Kind = kind,
            ContentType = contentType,
            Extension = extension,
            SizeBytes = sizeBytes,
            Width = width,
            Height = height,
            Sha256 = sha256,
        };
    }

    public Result UpdateTexts(string? title, IReadOnlyList<LocalizedText> texts)
    {
        ArgumentNullException.ThrowIfNull(texts);
        if (title is { Length: > TitleMaxLength } || texts.GroupBy(text => text.LanguageCode).Any(group => group.Count() > 1)
            || texts.Any(text => text.Text is null || text.Text.Length > AltMaxLength || text.Secondary is { Length: > CaptionMaxLength }
                || ContentBodyRules.HasControlCharacters(text.Text, false)))
        {
            return Error.Validation("Media.InvalidTexts", $"One alt text (max {AltMaxLength}) and caption (max {CaptionMaxLength}) per language.");
        }

        Title = string.IsNullOrWhiteSpace(title) ? null : title.Trim();
        Texts = texts
            .Where(text => !string.IsNullOrWhiteSpace(text.Text) || !string.IsNullOrWhiteSpace(text.Secondary))
            .Select(text => new LocalizedText(text.LanguageCode, text.Text.Trim(), string.IsNullOrWhiteSpace(text.Secondary) ? null : text.Secondary.Trim()))
            .ToList();
        return Result.Success();
    }

    public string? DefaultAlt(string languageCode) =>
        Texts.FirstOrDefault(text => text.LanguageCode == languageCode && !string.IsNullOrWhiteSpace(text.Text))?.Text;

    /// <summary>Display-only name: path segments and control characters removed, length bounded.</summary>
    public static string SafeDisplayName(string? fileName)
    {
        var name = Path.GetFileName((fileName ?? string.Empty).Replace('\\', '/'));
        var cleaned = new string(name.Where(character => !char.IsControl(character) && character is not ('/' or '\\' or '"' or '<' or '>')).ToArray()).Trim();
        if (cleaned.Length == 0)
        {
            return "file";
        }

        return cleaned.Length > FileNameMaxLength ? cleaned[^FileNameMaxLength..] : cleaned;
    }

    [GeneratedRegex("^[0-9]{4}/[0-9]{2}/[0-9a-f]{32}\\.(jpg|png|webp|gif)$", RegexOptions.CultureInvariant)]
    private static partial Regex StorageKeyPattern();
}
